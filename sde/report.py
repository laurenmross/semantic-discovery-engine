"""Human-readable outputs: the experiment summary and the per-run discovery report."""
from __future__ import annotations

import json
import statistics as st

from . import evidence

METRICS = [
    ("Relationship F1", lambda s: s["relationships"]["f1"]),
    ("Relationship precision", lambda s: s["relationships"]["precision"]),
    ("Relationship recall", lambda s: s["relationships"]["recall"]),
    ("Entity concept score", lambda s: s["entity_concept"]["mean_score"]),
    ("Entity kind accuracy", lambda s: s["entity_kind_accuracy"]),
    ("Column semantics (all)", lambda s: s["column_semantics_all"]["mean_score"]),
    ("Column semantics (non-obvious)", lambda s: s["column_semantics_non_obvious"]["mean_score"]),
    ("Invalid citations", lambda s: s["unsupported"]["invalid_citations"]),
    ("Overconfident errors", lambda s: s["unsupported"]["overconfident_errors"]),
    ("Causal statements (judge)", lambda s: s["unsupported"]["causal_statements_judge"]),
    ("Items to human-review", lambda s: s["human_review"]["total_items_to_review"]),
    ("Interpretation cost (USD)", lambda s: s["cost_usd"]),
    ("Interpretation time (s)", lambda s: s["seconds"]),
    ("Input tokens", lambda s: s["usage"]["input_tokens"]),
]


def _agg(vals):
    if not vals:
        return None
    return {"mean": st.mean(vals), "min": min(vals), "max": max(vals), "n": len(vals)}


def aggregate(scores: dict) -> dict:
    cells = {}
    for key, sc in scores.items():
        cfg, naming, _ = key.split("_")
        cells.setdefault((cfg, naming), []).append(sc)
    out = {}
    for cell, runs in cells.items():
        out[cell] = {name: _agg([f(r) for r in runs]) for name, f in METRICS}
    return out


def _fmt(a, digits=3):
    if a is None:
        return "–"
    if a["n"] == 1:
        return f"{a['mean']:.{digits}g}"
    return f"{a['mean']:.{digits}g} ({a['min']:.{digits}g}–{a['max']:.{digits}g})"


def decide(agg: dict, a: tuple, b: tuple, metric: str, higher_better=True) -> str:
    """Pre-registered rule: improvement only if the mean gap exceeds either cell's run-to-run range."""
    if a not in agg or b not in agg:
        return "not run"
    x, y = agg[a][metric], agg[b][metric]
    gap = (y["mean"] - x["mean"]) * (1 if higher_better else -1)
    noise = max(x["max"] - x["min"], y["max"] - y["min"])
    if x["n"] < 2 or y["n"] < 2:
        return f"gap {gap:+.3f}; too few runs to apply the decision rule"
    if gap > noise:
        return f"improvement (gap {gap:+.3f} > run-to-run range {noise:.3f})"
    if -gap > noise:
        return f"worse (gap {gap:+.3f}, range {noise:.3f})"
    return f"no detectable difference (gap {gap:+.3f}, range {noise:.3f})"


def summary_md(exp) -> str:
    out = exp.out
    ss = json.loads((out / "structural_scores.json").read_text())
    oc = json.loads((out / "outcome.json").read_text())
    scores = json.loads((out / "scores.json").read_text()) if (out / "scores.json").exists() else {}
    agg = aggregate(scores)
    L = ["# Experiment results: rel-avito", "",
         "_Generated by `python -m sde report`. Every number is computed from files in this folder._", ""]

    L += ["## Structural component alone (no LLM)", "",
          "| Edge set | Precision | Recall | F1 | Edges proposed |", "|---|---|---|---|---|"]
    for k in ("all_candidates", "preferred_parent", "feature_eligible"):
        v = ss[k]
        L.append(f"| {k.replace('_', ' ')} | {v['precision']} | {v['recall']} | {v['f1']} | {v['n_pred']} |")
    L.append(f"| primary keys | {ss['keys']['precision']} | {ss['keys']['recall']} | {ss['keys']['f1']} | {ss['keys']['n_pred']} |")
    L.append("")

    m = oc["models"]
    b = oc["baselines"].get("single_activity_count", {})
    L += ["## Outcome-driven component alone (predictive, held-out test)", "",
          f"- Label rows: {oc['n_rows']}. Positive rate: { {k: round(v, 3) for k, v in oc['base_rate'].items()} }",
          f"- Label check: recomputing the label from visit events agrees with the supplied label on {oc['label_check']['agreement']:.1%} of rows",
          f"- {len(oc['features'])} features built from inferred relationships; "
          f"{sum(s['significant_fdr05'] for s in oc['feature_stats'])} significant after Benjamini–Hochberg (q < 0.05)", "",
          "| Model | Validation AUROC | Test AUROC |", "|---|---|---|"]
    for k, v in m.items():
        if isinstance(v, dict):
            L.append(f"| {k.replace('_', ' ')}{' (selected on validation)' if k == m['selected_on_val'] else ''} | {v['val_auroc']:.3f} | {v['test_auroc']:.3f} |")
    if b:
        L.append(f"| baseline: best single past-activity count | {b['val_auroc']:.3f} | {b['test_auroc']:.3f} |")
    L.append("| baseline: base rate | 0.500 | 0.500 |")
    L.append("")

    if not agg:
        L += ["## LLM configurations", "", "_Not run yet: no recorded interpretation runs in `runs/`._", ""]
        return "\n".join(L)

    cols = [(c, n) for c in evidence.CONFIGS for n in evidence.NAMINGS if (c, n) in agg]
    L += ["## LLM configurations: mean (min–max across runs)", "",
          "| Metric | " + " | ".join(f"{c} / {n}" for c, n in cols) + " |",
          "|---|" + "---|" * len(cols)]
    for name, _ in METRICS:
        L.append(f"| {name} | " + " | ".join(_fmt(agg[c][name]) for c in cols) + " |")
    L.append("")
    L += ["## Pre-registered hypotheses (masked names = primary)", ""]
    for naming in ("masked", "original"):
        L.append(f"**{naming} names**")
        L.append(f"- H1 (B beats A on relationship F1): {decide(agg, ('A', naming), ('B', naming), 'Relationship F1')}")
        L.append(f"- H2a (C beats B on entity concepts): {decide(agg, ('B', naming), ('C', naming), 'Entity concept score')}")
        L.append(f"- H2b (C beats B on column semantics): {decide(agg, ('B', naming), ('C', naming), 'Column semantics (all)')}")
        L.append(f"- H2c (C beats B on non-obvious columns): {decide(agg, ('B', naming), ('C', naming), 'Column semantics (non-obvious)')}")
        L.append(f"- H3 (C does not add overconfident errors vs B): {decide(agg, ('B', naming), ('C', naming), 'Overconfident errors', higher_better=False)}")
        L.append("")
    total = sum(s["cost_usd"] + s["judge_cost_usd"] for s in scores.values())
    L.append(f"Total model cost of interpretation and judging: ${total:.2f} across {len(scores)} runs.")
    return "\n".join(L)


def discovery_report_md(exp, cfg: str, naming: str, run: int = 1) -> str | None:
    path = exp.out / "runs" / f"{cfg}_{naming}_r{run}.json"
    if not path.exists():
        return None
    rec = json.loads(path.read_text())
    o = rec["output"]
    s = exp.discover()
    namer = evidence.Namer(s, masked=(naming == "masked"))
    show_truth = naming == "masked"
    oc = json.loads((exp.out / "outcome.json").read_text())

    def truth_t(t):
        r = namer.unmask_table(t)
        return f" _(actually: {r})_" if show_truth and r else ""

    L = [f"# Discovery report: rel-avito, configuration {cfg}, {naming} names, run {run}", "",
         "This is the output of the system as a reader would receive it. **Computed facts** come from deterministic analysis. "
         "**Interpretations** are the LLM's hypotheses, each with its confidence and the evidence IDs it cites "
         f"(see `packets/{cfg}_{naming}.md`)." + (" Text in italics shows the real names, for evaluation only; the system never saw them." if show_truth else ""), ""]

    L += ["## 1. Inferred entities (interpretation)", "", "| Table | Concept | Kind | Confidence | Needs human check | Evidence |", "|---|---|---|---|---|---|"]
    for t in o["tables"]:
        L.append(f"| {t['table']}{truth_t(t['table'])} | {t['concept']} | {t['kind']} | {t['confidence']:.2f} | "
                 f"{'yes' if t['needs_human_validation'] else 'no'} | {', '.join(t['evidence'][:4])} |")
    L += ["", "## 2. Relationships accepted by the interpreter", "",
          "| Child column | Parent key | Confidence | Computed overlap evidence |", "|---|---|---|---|"]
    rels = {(r.child_table, r.child_column, r.parent_table): r for r in s.relationships}
    for r in o["relationships"]:
        ct, cc, pt = namer.unmask_table(r["from_table"]), namer.unmask_column(r["from_table"], r["from_column"]), namer.unmask_table(r["to_table"])
        ev = rels.get((ct, cc, pt))
        evs = (f"inclusion {ev.inclusion}, coverage {ev.parent_coverage}, rank {ev.parent_rank}"
               if ev else "not among computed candidates")
        L.append(f"| {r['from_table']}.{r['from_column']} | {r['to_table']}.{r['to_column']} | {r['confidence']:.2f} | {evs} |")
    L += ["", "## 3. Predictive associations (computed facts, held-out data)", "",
          f"Selected model test AUROC: {oc['models'][oc['models']['selected_on_val']]['test_auroc']:.3f} "
          f"(single best activity count: {oc['baselines'].get('single_activity_count', {}).get('test_auroc', float('nan')):.3f}). "
          "These are associations measured on time-ordered data. They are not causal and do not establish meaning.", ""]
    feats = {f["id"]: f for f in oc["features"]}
    L += ["| Feature | Validation AUROC | Direction | Stable across cutoffs | q (BH) | Permutation importance |", "|---|---|---|---|---|---|"]
    from .evidence import _path_str
    for stt in sorted(oc["feature_stats"], key=lambda d: -d["perm_importance_mean"])[:10]:
        f = feats[stt["feature"]]
        col = namer.col(f["table"], f["column"]) if f["column"] else namer.table(f["table"]) + " rows"
        L.append(f"| {f['agg']}({col}) via {_path_str(f['path'], namer)} | {stt['val_auroc']:.3f} | {stt['direction'].replace('_', ' ')} | "
                 f"{'yes' if stt['direction_stable'] else 'no'} | {stt['q_value_bh']:.2g} | {stt['perm_importance_mean']:.4f} |")
    L += ["", "## 4. Interpretations of the outcome evidence (hypotheses)", ""]
    for i in o["outcome_insights"]:
        L.append(f"- **{i['kind'].replace('_', ' ')}** (confidence {i['confidence']:.2f}): {i['statement']} _[{', '.join(i['evidence'][:5])}]_")
    L += ["", "## 5. Column meanings (interpretation)", "", "| Column | Meaning | Role | Confidence |", "|---|---|---|---|"]
    for c in o["columns"]:
        real = namer.unmask_column(c["table"], c["column"])
        tr = f" _(actually: {namer.unmask_table(c['table'])}.{real})_" if show_truth and real else ""
        L.append(f"| {c['table']}.{c['column']}{tr} | {c['meaning']} | {c['role']} | {c['confidence']:.2f} |")
    L += ["", "## 6. Unresolved ambiguities", ""] + [f"- {a['description']} _[{', '.join(a['evidence'][:4])}]_" for a in o["ambiguities"]]
    L += ["", "## 7. Suggested next investigations", ""] + [f"- {n}" for n in o["next_investigations"]]
    L += ["", "## 8. Limitations", "",
          "- Meanings are inferred from data patterns. Nothing here is an organisation-approved (governed) definition.",
          "- Relationship candidates come from value overlap. On dense integer keys, overlap alone is weak evidence (see range_density).",
          "- Predictive associations come from one dataset over about 3 weeks, with 3 training cutoffs. They may not hold in other periods.",
          "- Static tables (no time column) are used as-is and may contain information recorded after a cutoff.", ""]
    return "\n".join(L)


def write_all(exp):
    (exp.out / "summary.md").write_text(summary_md(exp))
    for naming in evidence.NAMINGS:
        md = discovery_report_md(exp, "C", naming)
        if md:
            (exp.out / f"discovery_report_C_{naming}.md").write_text(md)
