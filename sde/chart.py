"""Headline results chart for the README, generated from saved scores (never hand-edited).

Static SVG so GitHub can render it; light/dark colours follow the viewer's theme via
prefers-color-scheme. Palette and mark specs follow the reference data-viz palette:
categorical slots 1-3, <=24px bars with a 4px rounded data-end, direct value labels.
"""
from __future__ import annotations

import json
from pathlib import Path

from .datasets import ROOT
from .report import aggregate

ROWS = [("A", "A · schema only"), ("B", "B · + structure"), ("C", "C · + outcome evidence")]
PANELS = [
    ("Column semantics (recoverable)", "Understands what columns mean"),
    ("Planted signals recovered", "Finds the planted business signals"),
]

STYLE = """
  .surface { fill: #fcfcfb; }
  .ink { fill: #0b0b0b; } .ink2 { fill: #52514e; } .muted { fill: #898781; }
  .grid { stroke: #e1e0d9; } .base { stroke: #c3c2b7; } .range { stroke: #52514e; }
  .sA { fill: #2a78d6; } .sB { fill: #eb6834; } .sC { fill: #1baf7a; }
  @media (prefers-color-scheme: dark) {
    .surface { fill: #1a1a19; }
    .ink { fill: #f0efec; } .ink2 { fill: #c3c2b7; } .muted { fill: #898781; }
    .grid { stroke: #2c2c2a; } .base { stroke: #383835; } .range { stroke: #c3c2b7; }
    .sA { fill: #3987e5; } .sB { fill: #d95926; } .sC { fill: #199e70; }
  }
  text { font-family: system-ui, -apple-system, "Segoe UI", sans-serif; }
"""


def _bar(x0: float, y: float, w: float, h: float, cls: str) -> str:
    """Horizontal bar: square at the baseline, 4px rounded data-end."""
    if w <= 0:
        return ""
    r = min(4.0, w / 2, h / 2)
    return (f'<path class="{cls}" d="M{x0:.1f},{y:.1f} H{x0 + w - r:.1f} '
            f'Q{x0 + w:.1f},{y:.1f} {x0 + w:.1f},{y + r:.1f} V{y + h - r:.1f} '
            f'Q{x0 + w:.1f},{y + h:.1f} {x0 + w - r:.1f},{y + h:.1f} H{x0:.1f} Z"/>')


def svg(agg: dict, naming: str = "masked") -> str:
    W, H = 820, 330
    label_w = 190
    panel_x = [label_w + 10, label_w + 310]
    scale = 220.0
    row_y = [132, 172, 212]
    bar_h = 22
    out = [f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} {H}" width="{W}" height="{H}" '
           f'role="img" aria-labelledby="t d">',
           f"<style>{STYLE}</style>",
           f'<rect class="surface" width="{W}" height="{H}" rx="8"/>',
           '<title id="t">With names hidden, structure helps the AI understand the data; outcome evidence helps it discover what matters</title>',
           '<desc id="d">Synthetic SaaS warehouse, masked names, mean of 3 runs. '
           + "; ".join(f"{cfg}: {m} {agg[(cfg, naming)][m]['mean']:.0%}" for cfg, _ in ROWS for m, _ in PANELS)
           + ".</desc>",
           '<text class="ink" x="24" y="36" font-size="17" font-weight="600">With names hidden, structure helps the AI understand the data;</text>',
           '<text class="ink" x="24" y="58" font-size="17" font-weight="600">outcome evidence helps it discover what matters</text>',
           '<text class="ink2" x="24" y="80" font-size="13">Synthetic SaaS warehouse the model cannot have seen · every table and column name masked · mean of 3 runs</text>']
    for (metric, title), px in zip(PANELS, panel_x):
        out.append(f'<text class="ink" x="{px}" y="112" font-size="13" font-weight="600">{title}</text>')
        for frac in (0, 0.5, 1.0):
            gx = px + frac * scale
            cls = "base" if frac == 0 else "grid"
            out.append(f'<line class="{cls}" x1="{gx:.1f}" y1="{row_y[0] - 6}" x2="{gx:.1f}" y2="{row_y[-1] + bar_h + 6}" stroke-width="1"/>')
            out.append(f'<text class="muted" x="{gx:.1f}" y="{row_y[-1] + bar_h + 22}" font-size="11" text-anchor="middle">{frac:.0%}</text>')
        for (cfg, _), y in zip(ROWS, row_y):
            a = agg[(cfg, naming)][metric]
            w = a["mean"] * scale
            out.append(_bar(px, y, w, bar_h, f"s{cfg}"))
            if a["max"] - a["min"] > 0.005:
                x1, x2, cy = px + a["min"] * scale, px + a["max"] * scale, y + bar_h / 2
                out.append(f'<line class="range" x1="{x1:.1f}" y1="{cy}" x2="{x2:.1f}" y2="{cy}" stroke-width="1.5"/>')
                for xx in (x1, x2):
                    out.append(f'<line class="range" x1="{xx:.1f}" y1="{cy - 4}" x2="{xx:.1f}" y2="{cy + 4}" stroke-width="1.5"/>')
            lx = px + max(w, a["max"] * scale) + 8
            out.append(f'<text class="ink" x="{lx:.1f}" y="{y + 15}" font-size="13" font-weight="600">{a["mean"]:.0%}</text>')
    for (cfg, label), y in zip(ROWS, row_y):
        out.append(f'<text class="ink" x="24" y="{y + 15}" font-size="13">{label}</text>')
    out.append(f'<text class="muted" x="24" y="{H - 34}" font-size="11">Thin line = lowest–highest of 3 runs. With real column names, all three configurations scored ~100% on understanding.</text>')
    out.append(f'<text class="muted" x="24" y="{H - 18}" font-size="11">Generated by `python -m sde chart` from results/saas/scores.json. Details: EVALUATION.md, Experiment 2.</text>')
    out.append("</svg>")
    return "\n".join(o for o in out if o)


def write(dataset: str = "saas", path: Path | None = None) -> Path:
    scores = json.loads((ROOT / "results" / dataset / "scores.json").read_text())
    path = path or ROOT / "docs" / "results.svg"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(svg(aggregate(scores)))
    return path
